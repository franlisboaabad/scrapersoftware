    <h2 id="proyecto-title">El proyecto</h2>
    <p>
        Scraper busca empresas de cualquier rubro en Google Places, las guarda en MySQL
        y puede extraer emails de sus sitios web. Sirve para armar un directorio local
        por ciudad: restaurantes, clínicas, ferreterías, estudios, turismo u otro giro.
    </p>

    <ul class="fact-list">
        <li>
            <i class="fa-solid fa-magnifying-glass" aria-hidden="true"></i>
            Buscas por rubro, ciudad y cantidad (hasta 60).
        </li>
        <li>
            <i class="fa-solid fa-database" aria-hidden="true"></i>
            Cada resultado se guarda solo: búsquedas, empresas y correos.
        </li>
        <li>
            <i class="fa-solid fa-envelope" aria-hidden="true"></i>
            Desde el panel de búsqueda puedes extraer emails y descargar CSV.
        </li>
        <li>
            <i class="fa-solid fa-code" aria-hidden="true"></i>
            PHP, MySQL (Laragon) y Google Places API.
        </li>
    </ul>
